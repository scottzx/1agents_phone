import Foundation

/// Decision tier returned by the AgentCore Harness/Gateway.
public enum AgentCoreDecisionTier: String, Codable, Sendable {
    /// Action executed automatically within policy thresholds.
    case auto
    /// Action intercepted by Cedar Policy or flagged by model, requiring
    /// human-in-the-loop founder approval before proceeding.
    case escalate
    /// Action violated hard compliance boundaries and cannot be executed.
    case refuse
    /// Unclassified or legacy free-form model response.
    case unknown
}

/// Structured outcome of an AgentCore run.
public struct AgentCoreDecision: Codable, Sendable, Equatable {
    public let tier: AgentCoreDecisionTier
    public let summary: String
    public let reason: String?
    public let policyRule: String?
    public let rawOutput: String

    public init(
        tier: AgentCoreDecisionTier,
        summary: String,
        reason: String? = nil,
        policyRule: String? = nil,
        rawOutput: String = ""
    ) {
        self.tier = tier
        self.summary = summary
        self.reason = reason
        self.policyRule = policyRule
        self.rawOutput = rawOutput
    }
}

/// Status of a human approval / permission request triggered by policy escalation.
public enum SubagentApprovalStatus: String, Codable, Sendable {
    case pending
    case approved
    case rejected
}

/// A human-in-the-loop permission / approval request generated by an AgentCore escalation.
public struct SubagentApprovalRequest: Identifiable, Codable, Sendable, Equatable {
    public let id: String
    public let taskId: String
    public let title: String
    public let summary: String
    public let policyRule: String?
    public let reason: String?
    public var status: SubagentApprovalStatus
    public var feedback: String?
    public let createdAt: Date
    public var resolvedAt: Date?

    public init(
        id: String = UUID().uuidString,
        taskId: String,
        title: String,
        summary: String,
        policyRule: String? = nil,
        reason: String? = nil,
        status: SubagentApprovalStatus = .pending,
        feedback: String? = nil,
        createdAt: Date = Date(),
        resolvedAt: Date? = nil
    ) {
        self.id = id
        self.taskId = taskId
        self.title = title
        self.summary = summary
        self.policyRule = policyRule
        self.reason = reason
        self.status = status
        self.feedback = feedback
        self.createdAt = createdAt
        self.resolvedAt = resolvedAt
    }
}

/// Parser for outputs generated by AgentCore Harness / Gateway.
public enum AgentCoreParser {

    /// Detect decision tier and extract structured reasoning from AgentCore text.
    public static func parseDecision(from text: String) -> AgentCoreDecision {
        let lower = text.lowercased()

        // 1. Check for Cedar Policy interception patterns
        if lower.contains("forbid_large_amount") || lower.contains("金额超 20 万") || lower.contains("超 20 万阈值") {
            return AgentCoreDecision(
                tier: .escalate,
                summary: "金额超限，网关 Cedar 策略已拦截，需要创始人审批。",
                reason: "金额超出 200,000 元自动决策阈值，触发 forbid_large_amount 策略。",
                policyRule: "forbid_large_amount",
                rawOutput: text
            )
        }

        if lower.contains("forbid_new_counterparty") || lower.contains("首单") || lower.contains("新客户首单") {
            return AgentCoreDecision(
                tier: .escalate,
                summary: "新客户首单业务，网关 Cedar 策略已拦截，需要创始人审批。",
                reason: "首次合作对手方，触发 forbid_new_counterparty 策略。",
                policyRule: "forbid_new_counterparty",
                rawOutput: text
            )
        }

        if lower.contains("forbid_counterparty_overdue") || lower.contains("对手方有逾期") || lower.contains("逾期") {
            return AgentCoreDecision(
                tier: .refuse,
                summary: "对手方存在逾期记录，网关 Cedar 策略已拒绝执行。",
                reason: "客户存在逾期款项，触发 forbid_counterparty_overdue 策略。",
                policyRule: "forbid_counterparty_overdue",
                rawOutput: text
            )
        }

        if lower.contains("forbid_deviates_precedent") || lower.contains("偏离历史先例") {
            return AgentCoreDecision(
                tier: .escalate,
                summary: "商务条款偏离历史约定，网关 Cedar 策略已拦截。",
                reason: "条款偏离历史先例，触发 forbid_deviates_precedent 策略。",
                policyRule: "forbid_deviates_precedent",
                rawOutput: text
            )
        }

        // 2. Check for explicit bracketed tiers [escalate], [档位=escalate], etc.
        let tier: AgentCoreDecisionTier
        if text.contains("[escalate]") || text.contains("[档位=escalate]") || lower.contains("档位: escalate") {
            tier = .escalate
        } else if text.contains("[auto]") || text.contains("[档位=auto]") || lower.contains("档位: auto") {
            tier = .auto
        } else if text.contains("[refuse]") || text.contains("[档位=refuse]") || lower.contains("档位: refuse") {
            tier = .refuse
        } else {
            tier = .unknown
        }

        let summary = extractFirstLineOrSummary(text)
        return AgentCoreDecision(
            tier: tier,
            summary: summary,
            reason: nil,
            policyRule: nil,
            rawOutput: text
        )
    }

    private static func extractFirstLineOrSummary(_ text: String) -> String {
        let lines = text.components(separatedBy: .newlines)
            .map { $0.trimmingCharacters(in: .whitespacesAndNewlines) }
            .filter { !$0.isEmpty }
        return lines.first ?? text
    }
}

/// Heuristic router for deciding whether a subagent prompt belongs on cloud or local.
public enum AgentCoreTaskRouting {

    /// Keywords that indicate business domain tasks suitable for AgentCore cloud.
    public static let cloudKeywords: Set<String> = [
        "报价", "核价", "对账", "合同", "供应商", "税率", "续约", "折扣上限",
        "agentcore", "harness", "kb_search", "business_data", "policy",
        "pricing", "reconciliation", "supplier", "opc", "cedar"
    ]

    /// Inspect a prompt to check whether it contains business operations keywords.
    public static func isCloudTask(_ prompt: String) -> Bool {
        let lower = prompt.lowercased()
        for kw in cloudKeywords {
            if lower.contains(kw) { return true }
        }
        return false
    }
}

/// Transport protocol for executing prompts on an AgentCore remote backend.
public protocol AgentCoreTransport: Sendable {
    func invoke(
        prompt: String,
        actorId: String?,
        gatewayId: String?,
        harnessId: String?
    ) async throws -> String
}

/// Mock transport implementation for testing and preview.
public struct MockAgentCoreTransport: AgentCoreTransport {
    public let handler: @Sendable (String, String?) async throws -> String

    public init(handler: @escaping @Sendable (String, String?) async throws -> String) {
        self.handler = handler
    }

    public func invoke(
        prompt: String,
        actorId: String?,
        gatewayId: String?,
        harnessId: String?
    ) async throws -> String {
        try await handler(prompt, actorId)
    }
}
